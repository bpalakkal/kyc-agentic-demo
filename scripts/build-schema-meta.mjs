/**
 * build-schema-meta.mjs
 *
 * Derives schema/schema-meta.json from the canonical master + DD registry.
 * Single source of truth: schema/kyc_master_attribute_schema.json.
 * Consumed by both the UI (visibility, party tables) and the backend
 * (enum normalizer, DD completion gate).
 *
 * Run:  node scripts/build-schema-meta.mjs   (wired into `generate` / `prebuild`)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const SCHEMA_DIR = join(__dirname, '..', 'schema');

const master = JSON.parse(readFileSync(join(SCHEMA_DIR, 'kyc_master_attribute_schema.json'), 'utf8'));
const registry = JSON.parse(readFileSync(join(SCHEMA_DIR, 'dd-registry.json'), 'utf8'));

const defs = master.$defs || {};
const props = master.properties || {};
const ria = registry.attributes || {}; // RIA attr -> { party, verifiable, agent }

const isScalar = (b) => b && typeof b === 'object' && ('lineage' in b || 'id_flag' in b);
const valueNode = (b) => b?.lineage?.items?.properties?.value ?? null;
// value-enum ref: scalar (value.$ref) or array-of-enum (value.items.$ref)
const valueRef = (v) => v?.$ref ?? v?.items?.$ref ?? null;
const enumName = (ref) => (ref ? ref.split('/').pop() : null);
const riaName = (party, child) => (party ? `${party}_${child}` : child);
const agentOf = (key) => ria[key]?.agent ?? null;

const meta = { generatedAt: new Date().toISOString(), entityTypes: {}, attributes: {}, enums: {} };

// enum value-lists from $defs
for (const [name, d] of Object.entries(defs)) {
  if (d && typeof d === 'object' && Array.isArray(d.enum)) meta.enums[name] = d.enum;
}

function emitScalar(path, block, party = null, child = null) {
  // Party child property names are already prefixed (e.g. beneficial_owner_name),
  // which is exactly the DD-registry key — don't prefix again.
  const riaKey = party ? child : path;
  const vn = valueNode(block);
  const ref = valueRef(vn);
  meta.attributes[path] = {
    kind: 'scalar',
    party,
    child,
    valueEnum: ref ? enumName(ref) : null,
    multi: vn?.type === 'array' || undefined,   // array-valued (e.g. past_nationality, previous_names)
    identifiable: Object.hasOwn(block, 'id_flag'),
    verifiable: Object.hasOwn(block, 'verification_flag'),
    ddAgent: agentOf(riaKey),
    description: block?.description ?? null,
  };
}

for (const [name, block] of Object.entries(props)) {
  if (isScalar(block)) {
    emitScalar(name, block);
  } else if (block?.type === 'array' && block.items) {
    const children = block.items.properties || {};
    const childNames = Object.entries(children).filter(([, cb]) => isScalar(cb)).map(([c]) => c);
    meta.attributes[name] = { kind: 'array', party: name, children: childNames };
    for (const [c, cb] of Object.entries(children)) {
      if (isScalar(cb)) emitScalar(`${name}.${c}`, cb, name, c);
    }
  } else if (block?.type === 'object' && block.properties) {
    meta.attributes[name] = { kind: 'object', children: Object.keys(block.properties) };
  } else {
    meta.attributes[name] = {
      kind: 'scalar', party: null, valueEnum: null,
      identifiable: Object.hasOwn(block ?? {}, 'id_flag'),
      verifiable: Object.hasOwn(block ?? {}, 'verification_flag'),
      description: block?.description ?? null,
    };
  }
}

// per-entity-type applicability (keyed by cip_classification value)
const appl = master['x-entity-type-applicability'] || {};
for (const [etype, cfg] of Object.entries(appl)) {
  if (etype === '_description' || !cfg || typeof cfg !== 'object') continue;
  meta.entityTypes[etype] = {
    alias: cfg.alias ?? null,
    not_applicable: [...(cfg.not_applicable || [])].sort(),
    optional: [...(cfg.optional || [])].sort(),
  };
}

writeFileSync(join(SCHEMA_DIR, 'schema-meta.json'), JSON.stringify(meta, null, 2));
// Also emit an ESM module so both Node and Vite import it with zero JSON-attribute
// / resolveJsonModule config. schema-meta.json stays for inspection/tooling.
writeFileSync(join(SCHEMA_DIR, 'schema-meta.js'),
  '// AUTO-GENERATED by scripts/build-schema-meta.mjs — do not edit.\nexport default ' +
  JSON.stringify(meta) + ';\n');

const A = Object.values(meta.attributes);
console.log('[schema-meta] entity types:', Object.keys(meta.entityTypes).length);
console.log('[schema-meta] attributes:', A.length,
  '| scalar:', A.filter(a => a.kind === 'scalar').length,
  '| party/array:', A.filter(a => a.kind === 'array').length);
console.log('[schema-meta] enum-backed attrs:', A.filter(a => a.valueEnum).length,
  '| Country-valued:', A.filter(a => a.valueEnum === 'Country').length);
console.log('[schema-meta] enums:', Object.keys(meta.enums).length);
